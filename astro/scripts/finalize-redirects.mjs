#!/usr/bin/env node
/**
 * Trailing-slash variants must answer **308**, not the asset layer's 307.
 *
 * Why it matters: `/faq/` and `/faq` serve the same page, and Google consolidates
 * them only if the redirect is permanent. The live site answers 308 (Next
 * normalises trailing slashes that way). Cloudflare's Workers Assets answer 307
 * for the same request even with `html_handling: "drop-trailing-slash"` — measured
 * 2026-09-18 — which tells Google the move is temporary, so the slashed form keeps
 * whatever signal it has.
 *
 * An explicit `_redirects` rule wins over that default (verified on the preview:
 * two hand-written rules turned 307 into 308 while other pages stayed 307), so
 * this appends one rule per built page. Generated from the build, therefore it
 * cannot fall behind the page list — add a page and its slashed form is covered.
 *
 * Runs after `astro build`; see `npm run build`.
 */
import { readFileSync, readdirSync, existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));
const DIST = join(here, "../dist");
const RULES_PATH = join(DIST, "_redirects");

if (!existsSync(DIST)) {
  console.error("FAIL: dist/ is missing — run `astro build` first (this runs after it)");
  process.exit(1);
}

const htmlFiles = readdirSync(DIST, { recursive: true })
  .map(String)
  .filter((name) => name.endsWith(".html") && !name.endsWith("404.html"));

const paths = htmlFiles
  .map((name) => `/${name.replace(/index\.html$/, "").replace(/\.html$/, "")}`)
  .map((path) => (path === "/" ? "/" : path.replace(/\/$/, "")))
  .filter((path) => path !== "/");

/*
 * The retired routes need their slashed form too, and this is the check that found it.
 *
 * The generated block above only knows about **built** pages, so every retired route answered
 * `/x` → 301 and `/x/` → **404**. Measured on production 2026-09-23 after the #118 deploy: all
 * nine of them — /evidence, /leaderboard, /monitor, /timeline, /videos plus the four Jev pages
 * that had just moved — split that way.
 *
 * A 404 on the slashed form is the exact thing a 301 exists to prevent: if Google ever saw
 * `/monitor/`, the permanent-move signal never fires and the URL is simply gone. So the target is
 * the **final** destination rather than the bare source, because `/jev-guide/ → /jev-guide` would
 * work but adds a hop for no reason.
 *
 * Sources are read from the hand-written rules in `public/_redirects` (copied into dist by the
 * build), so retiring a route there covers both forms automatically and this cannot drift.
 */
const existingRules = existsSync(RULES_PATH) ? readFileSync(RULES_PATH, "utf8") : "";
const retired = existingRules
  .split("\n")
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith("#"))
  .map((line) => line.split(/\s+/))
  .filter(([, , status]) => status === "301")
  .map(([from, to]) => [from, to])
  // Param routes (`/profile/:nickname`) and splats have no single slashed form to add.
  .filter(([from]) => !from.includes(":") && !from.includes("*"));

const header =
  "# Trailing-slash variants, generated by scripts/finalize-redirects.mjs — do not hand-edit.\n" +
  "# Keep above the retired-route rules: first match wins, and these are exact paths.\n" +
  "# Built pages: /x/ → /x, 308 (Workers Assets answer 307 for these, which reads as temporary).\n";
const liveRules = [...new Set(paths)]
  .sort()
  .map((path) => `${path}/ ${path} 308`)
  .join("\n");
const retiredHeader = retired.length
  ? "# Retired routes: /x/ → the final destination, 301 (same status as the bare form).\n"
  : "";
const retiredRules = [...new Map(retired).entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([from, to]) => `${from}/ ${to} 301`)
  .join("\n");

const existing = existingRules;
if (existing.includes("# Trailing-slash variants")) {
  console.error("FAIL: dist/_redirects already carries generated rules — rebuild before running this twice");
  process.exit(1);
}

writeFileSync(RULES_PATH, `${header}${liveRules}\n${retiredHeader}${retiredRules}\n${existing}`);
console.log(
  `redirects: appended ${new Set(paths).size} trailing-slash rules ahead of the retired-route list` +
    (retired.length ? `, plus ${retiredRules ? retiredRules.split("\n").length : 0} for retired routes` : ""),
);
